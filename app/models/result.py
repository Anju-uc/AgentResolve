"""
Result Models module for AgentResolve.

Defines Pydantic models for structured output generated by the deterministic
forensic engine, including evidence items, rule execution results, attribution scores,
preventability ratings, counterfactual simulations, and final dispute reports.
"""

from enum import Enum
from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field
from app.models.incident import IncidentResult
from app.models.forensics import EvidenceProvenance, DisputeDriftResult


class AnalysisStatus(str, Enum):
    """Execution status of forensic analysis."""
    ANALYZED = "ANALYZED"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
    ERROR = "ERROR"


class FaultCategory(str, Enum):
    """The six canonical fault categories defined in rules.md."""
    USER_AMBIGUITY = "USER_AMBIGUITY"
    AGENT_MISJUDGMENT = "AGENT_MISJUDGMENT"
    MERCHANT_DATA_ERROR = "MERCHANT_DATA_ERROR"
    EXTERNAL_CHANGE = "EXTERNAL_CHANGE"
    USER_POST_PURCHASE_CHANGE = "USER_POST_PURCHASE_CHANGE"
    NO_FAULT_DETECTED = "NO_FAULT_DETECTED"


class PreventabilityRating(str, Enum):
    """Preventability ratings."""
    HIGH = "HIGH"
    LOW = "LOW"
    NOT_APPLICABLE = "N/A"


class EvidenceItem(BaseModel):
    """
    Individual inspectable evidence trace tied to a specific rule firing.
    """
    field: str = Field(..., description="Target attribute name (e.g. 'ram_gb').")
    evidence_statement: str = Field(..., description="Fact-based statement of observed evidence.")
    expected_value: Optional[Any] = Field(default=None, description="Expected value based on constraint/listing.")
    actual_value: Optional[Any] = Field(default=None, description="Actual recorded value at purchase/delivery.")
    provenance: Optional[EvidenceProvenance] = None


class RuleResult(BaseModel):
    """
    Result returned by an individual fault check rule execution.
    """
    category: FaultCategory = Field(..., description="Fault category checked by rule.")
    fired: bool = Field(..., description="True if rule criteria met based on evidence.")
    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        description="Inspectable list of evidence items supporting this rule."
    )
    evidence_factors: List[str] = Field(
        default_factory=list,
        description="Keys of evidence factors triggered for point scoring."
    )
    raw_points: int = Field(default=0, description="Sum of raw heuristic points before normalization.")


class FaultAttribution(BaseModel):
    """
    Attribution category paired with normalized attribution score (0 to 100).
    """
    category: FaultCategory = Field(..., description="Fault category name.")
    score: int = Field(..., description="Normalized score 0-100 based on relative evidence weights.")
    raw_points: int = Field(default=0, description="Raw heuristic points earned.")


class CounterfactualResult(BaseModel):
    """
    Structured outcome of deterministic counterfactual validation replay simulation.
    """
    applicable: bool = Field(
        ...,
        description="True if a counterfactual replay scenario applies to this transaction."
    )
    action: Optional[str] = Field(
        default=None,
        description="Hypothetical validation action (e.g. 'validate_ram')."
    )
    expected: Optional[Any] = Field(
        default=None,
        description="Expected attribute constraint value during simulation."
    )
    actual: Optional[Any] = Field(
        default=None,
        description="Actual merchant value encountered during simulation."
    )
    result: str = Field(
        ...,
        description="Simulated outcome statement (e.g. 'PURCHASE_WOULD_HAVE_BEEN_BLOCKED')."
    )
    narrative: str = Field(
        ...,
        description="Clear plain text statement of counterfactual simulation."
    )


class AnalysisResult(BaseModel):
    """
    Complete output generated by the AgentResolve forensic engine.
    """
    transaction_id: str = Field(..., description="ID of analyzed transaction.")
    status: AnalysisStatus = Field(..., description="ANALYZED or INSUFFICIENT_EVIDENCE.")
    incident: Optional[IncidentResult] = Field(
        default=None,
        description="Operational incident classification separate from fault attribution.",
    )
    missing_fields: List[str] = Field(
        default_factory=list,
        description="List of missing fields if status is INSUFFICIENT_EVIDENCE."
    )
    primary_fault: Optional[FaultAttribution] = Field(
        default=None,
        description="Highest-scoring fault attribution category. Null if INSUFFICIENT_EVIDENCE."
    )
    contributing_factors: List[FaultAttribution] = Field(
        default_factory=list,
        description="Secondary fired fault categories sorted by score."
    )
    preventability: PreventabilityRating = Field(
        default=PreventabilityRating.NOT_APPLICABLE,
        description="HIGH, LOW, or N/A preventability rating."
    )
    evidence_status: str = Field(default="COMPLETE", description="COMPLETE or INCOMPLETE.")
    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        description="Combined list of all inspectable evidence traces across fired rules."
    )
    counterfactual: Optional[CounterfactualResult] = Field(
        default=None,
        description="Deterministic counterfactual replay result."
    )
    economic_harm: Optional[float] = Field(default=None, description="Measured financial harm when the record establishes it.")
    harm_currency: Optional[str] = Field(default=None)
    dispute_drift: Optional[DisputeDriftResult] = Field(default=None, description="Supporting request-vs-dispute drift signal; never authoritative attribution.")
    data_flags: List[str] = Field(
        default_factory=list,
        description="Special data flags (e.g. ['DUPLICATE_CHARGE'])."
    )
    all_rule_results: List[RuleResult] = Field(
        default_factory=list,
        description="Raw execution results of all 5 independent fault checks for auditability."
    )
    forensic_score: int = Field(default=0, description="Deterministic evidence coverage score; not probability or confidence.")
    forensic_score_breakdown: Dict[str, int] = Field(default_factory=dict, description="Component evidence-coverage percentages.")
    explanation: str = Field(
        default="",
        description="Natural language summary generated by LLM adapter (or deterministic fallback)."
    )
    explanation_status: str = Field(
        default="NOT_REQUESTED",
        description="Status of LLM explanation generation (e.g. 'GENERATED', 'FALLBACK', 'UNAVAILABLE')."
    )
